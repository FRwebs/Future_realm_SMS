// Writes a runtime check (Zod) for every type in src/lib/domain/types.ts, so the shape the pages were written against can be compared with
// what the API actually answers. The types stay the single source of truth: run `npm run api:contracts` after changing one.
//
// The check is deliberately forgiving where the types are loose, and strict where they are exact:
//   - an optional field accepts a missing value or null (the API sends null for "nothing"),
//   - a union of words is a closed list, so a new word the API starts sending is noticed,
//   - anything this script cannot express (a generic, a mapped type) becomes "anything", never a guess.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";

const SOURCE = "src/lib/domain/types.ts";
const OUT = "src/lib/domain/types.zod.ts";
const file = ts.createSourceFile(SOURCE, readFileSync(SOURCE, "utf8"), ts.ScriptTarget.ESNext, true);
const names = new Set();
file.forEachChild((node) => {
  if ((ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) && node.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword) && !node.typeParameters?.length) names.add(node.name.text);
});

const lazy = (name) => `z.lazy(() => ${name}Schema)`;
function expr(node, ctx = null) {
  switch (node.kind) {
    case ts.SyntaxKind.StringKeyword: return "z.string()";
    case ts.SyntaxKind.NumberKeyword: return "z.number()";
    case ts.SyntaxKind.BooleanKeyword: return "z.boolean()";
    case ts.SyntaxKind.NullKeyword: return "z.null()";
    case ts.SyntaxKind.UndefinedKeyword: return "z.undefined()";
    case ts.SyntaxKind.UnknownKeyword: case ts.SyntaxKind.AnyKeyword: case ts.SyntaxKind.ObjectKeyword: return "z.unknown()";
  }
  if (ts.isLiteralTypeNode(node)) {
    const l = node.literal;
    if (l.kind === ts.SyntaxKind.NullKeyword) return "z.null()";
    if (ts.isStringLiteral(l)) return `z.literal(${JSON.stringify(l.text)})`;
    if (ts.isNumericLiteral(l)) return `z.literal(${l.text})`;
    if (l.kind === ts.SyntaxKind.TrueKeyword) return "z.literal(true)";
    if (l.kind === ts.SyntaxKind.FalseKeyword) return "z.literal(false)";
    return "z.unknown()";
  }
  if (ts.isParenthesizedTypeNode(node)) return expr(node.type, ctx);
  if (ts.isArrayTypeNode(node)) return `z.array(${expr(node.elementType, ctx)})`;
  if (ts.isTupleTypeNode(node)) return `z.tuple([${node.elements.map((e) => expr(ts.isNamedTupleMember(e) ? e.type : e, ctx)).join(", ")}])`;
  if (ts.isUnionTypeNode(node)) {
    const parts = node.types.map((t) => expr(t, ctx));
    return parts.length === 1 ? parts[0] : `z.union([${parts.join(", ")}])`;
  }
  if (ts.isTypeLiteralNode(node)) return object(node.members, ctx);
  if (ts.isTypeReferenceNode(node)) {
    const name = node.typeName.getText();
    const args = node.typeArguments ?? [];
    if (name === "Array" && args.length === 1) return `z.array(${expr(args[0], ctx)})`;
    if (name === "Record" && args.length === 2) return `z.record(${expr(args[0], ctx).replace(/^z\.union\(.*\)$/, "z.string()")}, ${expr(args[1], ctx)})`;
    if (name === "Date") return "z.string()";
    if (ctx?.local.has(name) && !args.length) return ctx.useLocal(name);
    if (names.has(name) && !args.length) { ctx?.usedDomain.add(name); return lazy(name); }
    return "z.unknown()";
  }
  return "z.unknown()";
}

function object(members, ctx = null) {
  const fields = [];
  for (const m of members) {
    if (!ts.isPropertySignature(m) || !m.type) continue;
    const key = m.name.getText();
    const base = expr(m.type, ctx);
    fields.push(`${/^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key.replace(/^["']|["']$/g, ""))}: ${m.questionToken ? `${base}.nullish()` : base}`);
  }
  return `z.looseObject({ ${fields.join(", ")} })`;
}

const out = [`// Generated by scripts/generate-domain-contracts.mjs from ${SOURCE}. Do not edit by hand; run \`npm run api:contracts\`.`, `import { z } from "zod";`, ""];
const declared = [];
file.forEachChild((node) => {
  if (!(ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) || !names.has(node.name.text)) return;
  const name = node.name.text;
  let body;
  if (ts.isInterfaceDeclaration(node)) body = node.heritageClauses?.length ? "z.looseObject({})" : object(node.members);
  else body = expr(node.type);
  declared.push(name);
  out.push(`export const ${name}Schema: z.ZodType<unknown> = ${body};`);
  out.push(`export const ${name}ListSchema = z.array(${name}Schema);`);
});
const generated = out.join("\n") + "\n";

/* ------------------------------------------------------------------------------------------------------------------------------ */
/* Second pass: the reads whose type is written beside the page that uses it (a type in the same file, or an inline shape).          */
/* A call site reads `observe<Shape>(localContracts["src/app/x/page.tsx#ab12cd"])`; the check for `Shape` is built from the type as    */
/* that file declares it, and filed under that key in src/lib/api/local-contracts.zod.ts.                                             */
/* ------------------------------------------------------------------------------------------------------------------------------ */
import { readdirSync, statSync } from "node:fs";
import { join } from "node:path";

const LOCAL_OUT = "src/lib/api/local-contracts.zod.ts";
const walk = (dir) => readdirSync(dir).flatMap((entry) => {
  const full = join(dir, entry);
  if (statSync(full).isDirectory()) return walk(full);
  return /\.tsx?$/.test(entry) && !entry.endsWith(".d.ts") && !entry.endsWith(".zod.ts") ? [full] : [];
});
const consts = [];
const entries = [];
const usedDomain = new Set();
const mangle = (path) => path.replace(/^src\//, "").replace(/\.tsx?$/, "").replace(/[^A-Za-z0-9]+/g, "_");

for (const path of walk("src")) {
  const text = readFileSync(path, "utf8");
  if (!text.includes("localContracts[")) continue;
  const source = ts.createSourceFile(path, text, ts.ScriptTarget.ESNext, true);
  const local = new Map();
  source.forEachChild((node) => {
    if ((ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) && !node.typeParameters?.length) local.set(node.name.text, node);
  });
  const made = new Map();
  const ctx = {
    local,
    usedDomain,
    useLocal(name) {
      const id = `${mangle(path)}_${name}`;
      if (!made.has(name)) {
        made.set(name, id);
        const node = local.get(name);
        const body = ts.isInterfaceDeclaration(node) ? (node.heritageClauses?.length ? "z.looseObject({})" : object(node.members, ctx)) : expr(node.type, ctx);
        consts.push(`const ${id}: z.ZodType<unknown> = ${body};`);
      }
      return `z.lazy(() => ${id})`;
    },
  };
  const visit = (node) => {
    if (ts.isCallExpression(node) && node.expression.getText() === "observe" && node.typeArguments?.length === 1 && node.arguments.length === 1 && ts.isElementAccessExpression(node.arguments[0]) && node.arguments[0].expression.getText() === "localContracts") {
      const key = node.arguments[0].argumentExpression.text;
      entries.push([key, expr(node.typeArguments[0], ctx)]);
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
}
entries.sort((a, b) => a[0].localeCompare(b[0]));
const seenKeys = new Set();
const localGenerated = [
  `// Generated by scripts/generate-domain-contracts.mjs from the types written beside the pages that read the API. Do not edit by hand; run \`npm run api:contracts\`.`,
  `import { z } from "zod";`,
  ...(usedDomain.size ? [`import { ${[...usedDomain].sort().map((n) => `${n}Schema`).join(", ")} } from "@/lib/domain/types.zod";`] : []),
  "",
  ...consts,
  "",
  `export const localContracts: Record<string, z.ZodType<unknown>> = {`,
  ...entries.filter(([key]) => (seenKeys.has(key) ? false : seenKeys.add(key))).map(([key, body]) => `  ${JSON.stringify(key)}: ${body},`),
  `};`,
  "",
].join("\n");

// `--check` writes nothing and fails when a file is out of date with the types: what CI runs, so a type changed without regenerating is caught.
const files = [[OUT, generated], [LOCAL_OUT, localGenerated]];
if (process.argv.includes("--check")) {
  const stale = files.filter(([path, content]) => (existsSync(path) ? readFileSync(path, "utf8") : "") !== content).map(([path]) => path);
  if (stale.length) {
    console.error(`${stale.join(", ")} out of date with the types — run \`npm run api:contracts\`.`);
    process.exit(1);
  }
  console.log(`${declared.length} domain contracts and ${seenKeys.size} page contracts are up to date.`);
} else {
  for (const [path, content] of files) writeFileSync(path, content);
  console.log(`${declared.length} contracts → ${OUT}; ${seenKeys.size} page contracts → ${LOCAL_OUT}`);
}
