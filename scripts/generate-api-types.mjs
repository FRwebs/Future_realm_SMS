// Reads the live OpenAPI document from the running API and writes the list of endpoints the web app is allowed to call
// (src/lib/api/api-routes.ts). The app's calls are checked against it — by the type system where a call names a route outright, and by
// tests/unit/api-contract.test.ts for every URL written in the source — so a misspelt or removed endpoint fails the build instead of
// failing for a customer. Run it with the API up (npm run dev:api) after adding, renaming or removing an endpoint:
//
//   npm run api:types              # reads http://127.0.0.1:4000
//   API_URL=https://… npm run api:types
import { writeFileSync } from "node:fs";

const base = (process.env.API_URL ?? "http://127.0.0.1:4000").replace(/\/$/, "");
const spec = `${base}/api/docs-json`;
const response = await fetch(spec).catch((error) => {
  console.error(`Could not reach ${spec} — start the API first (npm run dev:api).\n${error.message}`);
  process.exit(1);
});
if (!response.ok) {
  console.error(`${spec} answered ${response.status}.`);
  process.exit(1);
}
const document = await response.json();

const METHODS = ["get", "post", "put", "patch", "delete"];
const routes = Object.entries(document.paths)
  .flatMap(([path, item]) => METHODS.filter((method) => item[method]).map((method) => `${method.toUpperCase()} ${path}`))
  .sort((a, b) => a.localeCompare(b));

const body = routes.map((route) => `  ${JSON.stringify(route)},`).join("\n");

writeFileSync(
  "src/lib/api/api-routes.ts",
  `// Generated by scripts/generate-api-types.mjs from the API's OpenAPI document. Do not edit by hand; run \`npm run api:types\`.\n` +
    `export const API_ROUTES = [\n${body}\n] as const;\n\n` +
    `export type ApiRoute = (typeof API_ROUTES)[number];\n` +
    `/** \`GET /api/v1/students/{id}\` -> \`/api/v1/students/{id}\` */\n` +
    `export type ApiPath<Method extends string = string> = ApiRoute extends infer R ? (R extends \`\${Method} \${infer P}\` ? P : never) : never;\n`,
);
console.log(`${routes.length} endpoints → src/lib/api/api-routes.ts`);
